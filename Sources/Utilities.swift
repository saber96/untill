import AppKit
import SwiftUI

enum WheelLook: String, CaseIterable, Identifiable {
    case glass = "Glass", graphite = "Graphite", paper = "Paper"
    var id: Self { self }
}

enum ScreenshotMode: String, CaseIterable, Identifiable {
    case area = "Select area", display = "Entire display"
    var id: Self { self }
}

enum Utility: String {
    case pins = "Pinned Apps", music = "Music", clipboard = "Clipboard"
    case notes = "Notes", timers = "Timers", askAI = "Ask AI"
}

struct Countdown: Identifiable {
    let id = UUID()
    let ends: Date
    let minutes: Int
}

final class UtilityModel: ObservableObject {
    @Published var apps = UserDefaults.standard.stringArray(forKey: "pinnedApps") ?? [] {
        didSet { UserDefaults.standard.set(apps, forKey: "pinnedApps") }
    }
    @Published var note = UserDefaults.standard.string(forKey: "quickNote") ?? "" {
        didSet { UserDefaults.standard.set(note, forKey: "quickNote") }
    }
    @Published var historyEnabled = false {
        didSet {
            if historyEnabled { captureClipboard(force: true) }
            else { history.removeAll() }
        }
    }
    @Published private(set) var history: [String] = []
    @Published private(set) var currentClipboard = ""
    @Published private(set) var timers: [Countdown] = []
    static let timerMinutes = 1...180
    @Published var minutes = 5
    @Published var prompt = ""
    private var changeCount = -1

    func chooseApp() {
        let picker = NSOpenPanel()
        picker.directoryURL = URL(fileURLWithPath: "/Applications", isDirectory: true)
        picker.allowedContentTypes = [.applicationBundle]
        picker.allowsMultipleSelection = true
        picker.canChooseDirectories = false
        guard picker.runModal() == .OK else { return }
        for url in picker.urls where !apps.contains(url.path) { apps.append(url.path) }
    }

    func openApp(_ path: String) {
        NSWorkspace.shared.openApplication(at: URL(fileURLWithPath: path), configuration: .init()) { _, error in
            guard let error = error as NSError? else { return }
            Diagnostics.tools.error("Pinned app failed to open (\(error.domain, privacy: .public):\(error.code))")
            DispatchQueue.main.async { NSAlert(error: error).runModal() }
        }
    }

    func captureClipboard(force: Bool = false) {
        let board = NSPasteboard.general
        guard force || board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let hidden = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        let text = hidden.contains { board.types?.contains(.init($0)) == true } ? nil : board.string(forType: .string)
        currentClipboard = text ?? ""
        guard historyEnabled, let text, !text.isEmpty, text.utf8.count <= 100_000 else { return }
        history.removeAll { $0 == text }
        history.insert(text, at: 0)
        history = Array(history.prefix(15))
    }

    @discardableResult
    func copy(_ text: String) -> Bool {
        guard Self.hasText(text) else { return false }
        let board = NSPasteboard.general
        board.clearContents()
        guard board.setString(text, forType: .string) else {
            Diagnostics.tools.error("Could not copy text to the clipboard")
            NSSound.beep()
            return false
        }
        captureClipboard(force: true)
        return true
    }

    static func hasText(_ text: String) -> Bool {
        text.contains { !$0.isWhitespace }
    }

    func clearHistory() { history.removeAll() }

    func startTimer(at now: Date = .now) {
        guard Self.timerMinutes.contains(minutes) else {
            Diagnostics.tools.notice("Rejected timer outside the supported range")
            return
        }
        timers.append(Countdown(ends: now.addingTimeInterval(Double(minutes) * 60), minutes: minutes))
    }

    func cancelTimer(_ id: UUID) { timers.removeAll { $0.id == id } }

    func tick(clipboardVisible: Bool, at now: Date = .now) -> String? {
        if clipboardVisible || historyEnabled { captureClipboard() }
        guard !timers.isEmpty else { return nil }
        let expired = timers.filter { $0.ends <= now }
        guard !expired.isEmpty else { return nil }
        timers.removeAll { $0.ends <= now }
        return expired.count == 1 ? "Your \(expired[0].minutes)-minute timer finished." : "\(expired.count) timers finished."
    }
}

struct UtilityView: View {
    let utility: Utility
    @ObservedObject var model: UtilityModel
    let actions: ToolActions

    var body: some View {
        Group {
            switch utility {
            case .pins:
                VStack(alignment: .leading) {
                    Button("Add Apps…", action: model.chooseApp)
                    if model.apps.isEmpty { Text("Add apps to launch them from the ring.").foregroundStyle(.secondary) }
                    List(model.apps, id: \.self) { path in
                        HStack {
                            Button { model.openApp(path) } label: {
                                Label {
                                    Text(URL(fileURLWithPath: path).deletingPathExtension().lastPathComponent)
                                } icon: {
                                    Image(nsImage: NSWorkspace.shared.icon(forFile: path)).resizable().frame(width: 20, height: 20)
                                }
                            }.buttonStyle(.borderless)
                            Spacer()
                            Button { model.apps.removeAll { $0 == path } } label: {
                                Image(systemName: "minus.circle")
                            }.buttonStyle(.borderless).accessibilityLabel("Unpin app")
                        }
                    }
                }
            case .music:
                VStack(alignment: .leading, spacing: 14) {
                    Text("Controls the current system media player.").foregroundStyle(.secondary)
                    HStack {
                        Button { actions.media(18) } label: { Label("Previous", systemImage: "backward.end") }
                        Button { actions.media(16) } label: { Label("Play / Pause", systemImage: "playpause") }
                        Button { actions.media(17) } label: { Label("Next", systemImage: "forward.end") }
                    }
                    Spacer()
                }
            case .clipboard:
                VStack(alignment: .leading) {
                    HStack {
                        Toggle("Keep text history for this session", isOn: $model.historyEnabled)
                        Spacer()
                        Button("Clear History", action: model.clearHistory).disabled(model.history.isEmpty)
                    }
                    Text("Current clipboard").font(.headline)
                    ScrollView {
                        Text(model.currentClipboard.isEmpty ? "No shareable text on the clipboard." : model.currentClipboard)
                            .textSelection(.enabled)
                            .frame(maxWidth: .infinity, alignment: .leading)
                    }.frame(maxHeight: 95)
                    if model.historyEnabled {
                        List(model.history, id: \.self) { text in
                            Button { model.copy(text) } label: {
                                Label(String(text.prefix(180)), systemImage: "document.on.document").lineLimit(2)
                            }.buttonStyle(.borderless)
                        }
                    }
                    Spacer(minLength: 0)
                }
            case .notes:
                VStack(alignment: .leading) {
                    TextEditor(text: $model.note).font(.body).accessibilityLabel("Quick note")
                    Button("Copy Note") { model.copy(model.note) }.disabled(!UtilityModel.hasText(model.note))
                }
            case .timers:
                VStack(alignment: .leading) {
                    HStack {
                        Stepper("\(model.minutes) min", value: $model.minutes, in: UtilityModel.timerMinutes)
                        Button("Start Timer") { model.startTimer() }
                    }
                    if model.timers.isEmpty { Text("No active timers").foregroundStyle(.secondary) }
                    List(model.timers) { timer in
                        HStack {
                            Text("\(timer.minutes)-minute timer")
                            Spacer()
                            Text(timer.ends, style: .timer).monospacedDigit()
                            Button("Cancel") { model.cancelTimer(timer.id) }.buttonStyle(.borderless)
                        }
                    }
                }
            case .askAI:
                VStack(alignment: .leading) {
                    Text("Write a prompt, then paste it into ChatGPT to send it.").foregroundStyle(.secondary)
                    TextEditor(text: $model.prompt).accessibilityLabel("Prompt for ChatGPT")
                    Button("Copy Prompt and Open ChatGPT") {
                        guard model.copy(model.prompt), let url = URL(string: "https://chatgpt.com/") else { return }
                        if !NSWorkspace.shared.open(url) {
                            Diagnostics.tools.error("Could not open the ChatGPT website")
                            let alert = NSAlert()
                            alert.messageText = "Could not open ChatGPT"
                            alert.informativeText = "Your prompt was copied to the clipboard."
                            alert.runModal()
                        }
                    }
                    .disabled(!UtilityModel.hasText(model.prompt))
                }
            }
        }
        .padding(16)
        .frame(width: 440, height: 300)
    }
}
